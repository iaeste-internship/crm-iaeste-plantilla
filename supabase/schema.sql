-- Perfil de cada usuario (se crea solo al registrarse)
create table public.profiles (
  id      uuid primary key references auth.users (id) on delete cascade,
  nombre  text not null,
  rol     text not null default 'miembro' check (rol in ('miembro', 'admin')),
  creado  timestamptz not null default now()
);

-- Empresas a contactar
create table public.empresas (
  id                uuid primary key default gen_random_uuid(),
  nombre            text not null,
  cif               text default '',
  sector            text default '',
  contacto          text default '',
  email             text default '',
  telefono          text default '',
  direccion         text,
  responsable       uuid references public.profiles (id) on delete set null,
  estado            text not null default 'sin_contactar',
  notas             text default '',
  proximo_contacto  date,
  historica         boolean not null default false,
  actualizado       timestamptz not null default now(),
  actualizado_por   text default ''
);

create index empresas_responsable_idx on public.empresas (responsable);
create index empresas_estado_idx      on public.empresas (estado);

-- Opcional (recomendado): impide CIF repetidos. Ignora los vacíos.
-- create unique index empresas_cif_unico on public.empresas (upper(cif)) where coalesce(cif, '') <> '';

-- Historial de todo lo que pasa (de aquí salen los puntos)
create table public.historial (
  id               bigint generated by default as identity primary key,
  empresa_id       uuid references public.empresas (id) on delete set null,
  empresa_nombre   text not null default '',
  usuario_id       uuid references public.profiles (id) on delete set null,
  usuario_nombre   text not null default 'sistema',
  accion           text not null,
  detalle          text not null default '',
  estado_anterior  text,
  estado_nuevo     text,
  creado           timestamptz not null default now()
);

create index historial_empresa_idx on public.historial (empresa_id);
create index historial_usuario_idx on public.historial (usuario_id);
create index historial_creado_idx  on public.historial (creado);

-- Prácticas conseguidas por empresa y año (marcan la empresa como histórica)
create table public.practicas (
  id                 bigint generated by default as identity primary key,
  empresa_id         uuid not null references public.empresas (id) on delete cascade,
  anio               integer,
  num_practicas      integer,
  notas              text,
  creado             timestamptz not null default now(),
  creado_por         uuid default auth.uid(),
  creado_por_nombre  text
);

create index practicas_empresa_idx on public.practicas (empresa_id);

-- Dominios de email desechables que no pueden registrarse
create table public.dominios_bloqueados (
  dominio  text primary key,
  creado   timestamptz not null default now()
);

